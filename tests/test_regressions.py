from pathlib import Path
import unittest
ROOT=Path(__file__).resolve().parents[1]
html=(ROOT/'index.html').read_text()
css=(ROOT/'styles.css').read_text()
theme=(ROOT/'bookshop-v28.css').read_text()
js=(ROOT/'app.js').read_text()
worker=(ROOT/'worker/index.js').read_text()
adapter=(ROOT/'api/_adapter.js').read_text()

class RegressionTests(unittest.TestCase):
    def test_interface(self):
        self.assertIn('read<span class="wordmark-amp">&amp;</span>found',html)
        self.assertIn('We should talk about books.',html)
        self.assertIn('bookshop-v28.css?v=29',html)
        self.assertIn('bookshop-v28.js?v=28',html)
        self.assertIn('Start with the books you love',html)
        self.assertIn('Use an example',html)
        self.assertIn('Normal People',html)
        self.assertIn('Agatha Christie',html)
        self.assertNotIn('class="hero-art"',html)
        self.assertNotIn('AN IMAGINARY PRESS',html)
        self.assertNotIn('THE READING ROOM',html)
        self.assertNotIn('STEP 1 OF 4',html)
        self.assertEqual(html.count('Made by Drew'),1)
        self.assertNotIn('class="footer-note"',html)
        self.assertIn('About Read &amp; Found',html)
        self.assertNotIn('more or less',html)
        self.assertIn('site-footer compact-footer',html)
        self.assertIn('Help cover running costs',html)
        self.assertIn('Support the project',html)
        self.assertIn('AI and hosting costs',html)
        self.assertNotIn('buy me a drink',html.lower())
        self.assertNotIn('buy me a coffee',html.lower())
        self.assertIn('resizeFavourites()', (ROOT/'refinements-v26.js').read_text())
    def test_about_and_portrait(self):
        self.assertIn('Why I made this',html)
        self.assertIn('for good, not evil (or profit)',html)
        self.assertIn('estimated to consume less water',html)
        self.assertIn("Hey, I'm Drew Timms",html)
        self.assertIn('bookshop notebook',theme)
        self.assertIn('.book-cover.has-real-cover',theme)
        self.assertIn('prefers-reduced-motion',theme)
        self.assertIn('character-hint.is-visible',theme)
        self.assertIn('1050',(ROOT/'bookshop-v28.js').read_text())
    def test_bookish_typography(self):
        self.assertNotIn('IBM+Plex+Mono',html)
        self.assertNotIn("--ui-font:'IBM Plex Mono'",theme)
        self.assertIn("--ui-font:'Source Serif 4'",theme)
        self.assertIn('.hero-author-note {font:italic 400 17px',theme)
        self.assertIn('font:600 18px/1.25 var(--ui-font)',theme)
        self.assertIn('.character-hint {opacity:0;transition:opacity .2s;font:11px var(--font-sans)',theme)
    def test_backend_unchanged(self):
        self.assertIn('import worker',adapter)
        self.assertNotIn('_adapter_original.js',adapter)
        self.assertIn('OPENAI_API_KEY',worker)
        self.assertIn('researchNotes',worker)
        self.assertIn('has-real-cover',js)
        self.assertIn('loadShareCover',js)
        self.assertIn('bookshopUrl',js)

    def test_editorial_round_30(self):
        self.assertIn('editorial-v30.css?v=30',html)
        self.assertIn('id="loadingKicker"',html)
        self.assertIn('Question 1 of 3',html)
        self.assertIn('portraitStartingPoint',html)
        self.assertIn('data-feedback="yes"',html)
        self.assertIn('Help cover running costs',html)
        self.assertIn("state.answers.length+1",js)
        self.assertIn("index/3*100",js)
        self.assertNotIn("index+1)/3*100",js)
        self.assertIn('allSources',js)
        self.assertIn("row.className = 'book-row'",js)
        self.assertIn('40–60 words',worker)
        self.assertIn("'/languages/eng'",worker)
        self.assertIn("'list_helpful'",worker)
        self.assertIn("'list_not_helpful'",worker)

    def test_ruled_handwritten_answers(self):
        sheet=(ROOT/'editorial-v30.css').read_text()
        self.assertIn('Patrick+Hand',html)
        self.assertIn('editorial-v30.css?v=31',html)
        self.assertIn("--answer-line-height: 32px",sheet)
        self.assertIn("--answer-line-height: 30px",sheet)
        self.assertIn("background-attachment: local",sheet)
        self.assertIn("font-family: 'Patrick Hand'",sheet)

    def test_signature_animation_and_selective_lowercase(self):
        stamp=(ROOT/'signature-v32.css').read_text()
        self.assertIn('signature-v32.css?v=32',html)
        self.assertIn('app.js?v=32',html)
        self.assertIn('class="reading-stamp"',html)
        self.assertIn('bookshop-stamp',stamp)
        self.assertIn('prefers-reduced-motion:reduce',stamp)
        self.assertIn('text-transform:lowercase',stamp)
        self.assertNotIn('.book-title {text-transform',stamp)
        self.assertIn("stamp-revealed",js)
        self.assertIn("requestAnimationFrame",js)

if __name__=='__main__': unittest.main()
